// Her kategorinin İLK [TagCategory.featuredCount] etiketi "öne çıkan"dır:
// arayüz varsayılan olarak yalnızca bunları gösterir, kalanı arama
// kutusuna yazınca bulunur. Bu yüzden liste sırası önemlidir.

/// Türkçe kurallarına göre küçük harf. Dart'ın toLowerCase()'i
/// 'İ'→'i̇' (birleşik nokta) ve 'I'→'i' yapar; ikisi de yanlıştır.
/// Veritabanına yazılan kanonik biçim budur; tag_catalog tablosu da
/// (docs/schema.sql §6) aynı kuralla üretilir.
String turkishLower(String s) {
  return s.replaceAll('İ', 'i').replaceAll('I', 'ı').toLowerCase();
}

/// Arama karşılaştırması için katlama: turkishLower'a ek olarak ı/i
/// ayrımını kaldırır. Böylece "it" yazan da "IT Destek"i, "ıspa" yazan
/// da "Isparta"yı bulur. Yalnızca aramada kullanılır; veritabanına
/// yazımda her zaman [turkishLower] geçerlidir.
String searchFold(String s) => turkishLower(s).replaceAll('ı', 'i');

/// Veritabanındaki küçük harfli etiketi görünen haline çevirir
/// (örn. "yapay zeka & veri" → "Yapay Zeka & Veri").
String displayTag(String dbTag) => _displayByDb[dbTag] ?? dbTag;

/// Veritabanı etiketinin kategori adı (örn. "react" →
/// "Yazılım — Web, Mobil & Oyun"). Listede olmayan etiket için null.
String? tagCategory(String dbTag) => _categoryByDb[dbTag];

final Map<String, String> _displayByDb = {
  for (final category in tagCategories)
    for (final tag in category.tags) turkishLower(tag): tag,
};

final Map<String, String> _categoryByDb = {
  for (final category in tagCategories)
    for (final tag in category.tags) turkishLower(tag): category.name,
};

class TagCategory {
  const TagCategory({
    required this.name,
    required this.tags,
    this.featuredCount = 8,
  });

  final String name;

  /// Kategorinin tüm etiketleri; ilk [featuredCount] tanesi öne çıkandır.
  final List<String> tags;

  /// Arama yapılmadığında gösterilecek etiket sayısı (listenin başından).
  final int featuredCount;

  /// Varsayılan görünümde saklanan (yalnızca aramayla bulunan) etiket sayısı.
  int get hiddenCount => tags.length - featuredCount;
}

